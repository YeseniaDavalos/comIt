// Declarar las variables
let numero1 = 10;
let numero2 = 5;

// Comparar las variables y mostrar el mensaje correspondiente utilizando operador ternario
console.log(numero1 > numero2 
? 'La variable numero1 es más grande que la variable numero2' 
: 'La variable numero1 no es más grande que la variable numero2'
);

// Probar diferentes valores para las variables
numero1 = 3;
numero2 = 8;

console.log(numero1 > numero2 
? 'La variable numero1 es más grande que la variable numero2' 
: 'La variable numero1 no es más grande que la variable numero2'
);
