// Declarar la variable numero y asignarle el valor inicial
let numero = 10;

// Verificar si el número es par
if (numero % 2 === 0) {
console.log('El número es par');
} else {
console.log('El número no es par');
}

// Cambiar el valor de la variable numero a un número impar y volver a ejecutar
numero = 7;

if (numero % 2 === 0) {
console.log('El número es par');
} else {
console.log('El número no es par');
}
