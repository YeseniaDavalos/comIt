// Declarar la variable numero y asignarle el valor inicial
let numero = 10;

// Verificar si el número es par utilizando operador ternario
console.log(numero % 2 === 0 ? 'El número es par' : 'El número no es par');

// Cambiar el valor de la variable numero a un número impar y volver a ejecutar
numero = 7;

// Verificar nuevamente utilizando operador ternario
console.log(numero % 2 === 0 ? 'El número es par' : 'El número no es par');
